/// Thermal Receipt-Style Printable Restock Shopping Checklist ("Listahan sa Pamamalengke").
/// Allows store owners to view, copy, share, or print a receipt-formatted guide
/// of all low-stock items with suggested purchase quantities and estimated capital (puhunan).
class PrintableRestockReceiptSheet extends StatefulWidget {
  const PrintableRestockReceiptSheet({super.key});

  static Future<void> show(BuildContext context) {
    return showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (_) => const PrintableRestockReceiptSheet(),
    );
  }

  @override
  State<PrintableRestockReceiptSheet> createState() =>
      _PrintableRestockReceiptSheetState();
}

class _PrintableRestockReceiptSheetState
    extends State<PrintableRestockReceiptSheet> {
  final GlobalKey _receiptBoundaryKey = GlobalKey();
  bool _isSharing = false;

  int _suggestedBuyQty(Product p) {
    final target = (p.lowStockLevel * 2).clamp(5, 100);
    final diff = target - p.stockQty;
    return diff > 0 ? diff : p.lowStockLevel.clamp(5, 50);
  }

  int _unitEstimatedCostCents(Product p) {
    return p.costCents > 0 ? p.costCents : (p.priceCents * 80) ~/ 100;
  }

  String _buildPlainTextReceipt({
    required String storeName,
    required String ownerName,
    required List<Product> items,
    required bool isTl,
  }) {
    final nowStr = DateFormat('MMM d, yyyy h:mm a').format(DateTime.now());
    final sb = StringBuffer();
    sb.writeln('================================');
    sb.writeln('  ${storeName.toUpperCase()}');
    if (ownerName.isNotEmpty) {
      sb.writeln('  Owner: $ownerName');
    }
    sb.writeln('  ${isTl ? 'LISTAHAN NG PAMAMALENGKE' : 'RESTOCK SHOPPING RECEIPT'}');
    sb.writeln('  Date: $nowStr');
    sb.writeln('================================');
    sb.writeln('ITEM              LEFT   BUY   EST.COST');
    sb.writeln('--------------------------------');

    int totalBudgetCents = 0;
    for (final p in items) {
      final buyQty = _suggestedBuyQty(p);
      final estCost = buyQty * _unitEstimatedCostCents(p);
      totalBudgetCents += estCost;
      final nameCol = p.name.length > 16
          ? '${p.name.substring(0, 15)}.'
          : p.name.padRight(16);
      sb.writeln(
        '[ ] $nameCol x${p.stockQty.toString().padLeft(2)} -> +${buyQty.toString().padLeft(2)}  ${CurrencyFormatter.format(estCost)}',
      );
    }

    sb.writeln('--------------------------------');
    sb.writeln('ITEMS TO RESTOCK: ${items.length}');
    sb.writeln(
      '${isTl ? 'TANTIYANG PUHUNAN' : 'EST. CAPITAL NEEDED'}: ${CurrencyFormatter.format(totalBudgetCents)}',
    );
    sb.writeln('================================');
    sb.writeln('   Generated by SariMe POS');
    return sb.toString();
  }

  Future<void> _shareReceiptImageOrText({
    required String plainText,
    required bool isTl,
  }) async {
    if (_isSharing) return;
    HapticFeedback.mediumImpact();
    setState(() => _isSharing = true);

    try {
      if (!kIsWeb && !Platform.environment.containsKey('FLUTTER_TEST')) {
        final boundary = _receiptBoundaryKey.currentContext?.findRenderObject()
            as RenderRepaintBoundary?;
        if (boundary != null) {
          final ui.Image image = await boundary.toImage(pixelRatio: 2.5);
          final ByteData? byteData =
              await image.toByteData(format: ui.ImageByteFormat.png);
          if (byteData != null) {
            final Uint8List pngBytes = byteData.buffer.asUint8List();
            final tempDir = await getTemporaryDirectory();
            final filePath = p.join(
              tempDir.path,
              'restock_receipt_${DateTime.now().millisecondsSinceEpoch}.png',
            );
            final file = File(filePath);
            await file.writeAsBytes(pngBytes);

            await Share.shareXFiles(
              [XFile(file.path)],
              text: plainText,
              subject: isTl
                  ? 'Listahan ng Pamamalengke (Restock Receipt)'
                  : 'Restock Shopping Receipt',
            );
            if (mounted) setState(() => _isSharing = false);
            return;
          }
        }
      }
      await Share.share(plainText);
    } catch (_) {
      await Clipboard.setData(ClipboardData(text: plainText));
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(
              isTl
                  ? 'Nakopya na ang listahan ng pamamalengke!'
                  : 'Restock receipt copied to clipboard!',
            ),
            backgroundColor: AppTheme.primaryGreen,
          ),
        );
      }
    } finally {
      if (mounted) setState(() => _isSharing = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final productProv = context.watch<ProductProvider>();
    final themeProv = context.watch<ThemeProvider?>();
    final isTl = context.watch<LanguageProvider?>()?.isTagalog ?? false;

    final storeName = themeProv?.storeName ?? 'SariMe Store';
    final ownerName = themeProv?.ownerName ?? '';
    final storeAddress = themeProv?.storeAddress ?? '';

    final lowStockItems = productProv.lowStockProducts.isNotEmpty
        ? productProv.lowStockProducts
        : productProv.allProducts
            .where((p) => p.stockQty <= p.lowStockLevel)
            .toList();

    int totalBudgetCents = 0;
    for (final p in lowStockItems) {
      totalBudgetCents += _suggestedBuyQty(p) * _unitEstimatedCostCents(p);
    }

    final plainText = _buildPlainTextReceipt(
      storeName: storeName,
      ownerName: ownerName,
      items: lowStockItems,
      isTl: isTl,
    );

    return Container(
      height: MediaQuery.of(context).size.height * 0.85,
      decoration: BoxDecoration(
        color: theme.colorScheme.surface,
        borderRadius: AppConstants.borderRadiusTopSheet,
      ),
      child: SafeArea(
        child: Column(
          children: [
            Container(
              margin: const EdgeInsets.only(top: 10),
              width: 40,
              height: 4,
              decoration: BoxDecoration(
                color: Colors.grey.withOpacity(0.35),
                borderRadius: BorderRadius.circular(2),
              ),
            ),
            Padding(
              padding: const EdgeInsets.fromLTRB(16, 12, 16, 8),
              child: Row(
                children: [
                  const Icon(
                    Icons.receipt_long_rounded,
                    color: AppTheme.primaryGreen,
                  ),
                  const SizedBox(width: 8),
                  Expanded(
                    child: Text(
                      isTl
                          ? 'Printable Restock List (Receipt Style)'
                          : 'Printable Restock Receipt Guide',
                      style: const TextStyle(
                        fontSize: 16,
                        fontWeight: FontWeight.w800,
                      ),
                    ),
                  ),
                  IconButton(
                    icon: const Icon(Icons.close_rounded),
                    onPressed: () => Navigator.pop(context),
                  ),
                ],
              ),
            ),
            const Divider(height: 1),

            Expanded(
              child: SingleChildScrollView(
                padding: const EdgeInsets.all(16),
                child: RepaintBoundary(
                  key: _receiptBoundaryKey,
                  child: Container(
                    padding: const EdgeInsets.all(18),
                    decoration: BoxDecoration(
                      color: const Color(0xFFFFFDF7), // Thermal paper cream white
                      borderRadius: BorderRadius.circular(12),
                      border: Border.all(
                        color: const Color(0xFFCBD5E1),
                        width: 1.2,
                      ),
                      boxShadow: [
                        BoxShadow(
                          color: Colors.black.withOpacity(0.08),
                          blurRadius: 12,
                          offset: const Offset(0, 4),
                        ),
                      ],
                    ),
                    child: DefaultTextStyle(
                      style: const TextStyle(
                        fontFamily: 'monospace',
                        color: Color(0xFF0F172A),
                        fontSize: 12,
                      ),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.stretch,
                        children: [
                          Text(
                            storeName.toUpperCase(),
                            textAlign: TextAlign.center,
                            style: const TextStyle(
                              fontSize: 16,
                              fontWeight: FontWeight.w900,
                              letterSpacing: 0.6,
                              color: Color(0xFF0F172A),
                            ),
                          ),
                          if (ownerName.isNotEmpty)
                            Text(
                              'Owner: $ownerName',
                              textAlign: TextAlign.center,
                              style: const TextStyle(
                                fontSize: 11.5,
                                color: Color(0xFF475569),
                              ),
                            ),
                          if (storeAddress.isNotEmpty)
                            Text(
                              storeAddress,
                              textAlign: TextAlign.center,
                              style: const TextStyle(
                                fontSize: 11,
                                color: Color(0xFF64748B),
                              ),
                            ),
                          const SizedBox(height: 4),
                          Text(
                            isTl
                                ? '*** GABAY SA PAMAMALENGKE (RESTOCK) ***'
                                : '*** RESTOCK SHOPPING CHECKLIST ***',
                            textAlign: TextAlign.center,
                            style: const TextStyle(
                              fontSize: 11.5,
                              fontWeight: FontWeight.w800,
                              color: AppTheme.primaryGreen,
                            ),
                          ),
                          Text(
                            DateFormat('MMM d, yyyy • h:mm a')
                                .format(DateTime.now()),
                            textAlign: TextAlign.center,
                            style: const TextStyle(
                              fontSize: 10.5,
                              color: Color(0xFF64748B),
                            ),
                          ),
                          const Padding(
                            padding: EdgeInsets.symmetric(vertical: 8),
                            child: Text(
                              '----------------------------------------',
                              textAlign: TextAlign.center,
                              maxLines: 1,
                              overflow: TextOverflow.clip,
                            ),
                          ),
                          Row(
                            children: [
                              Expanded(
                                flex: 4,
                                child: Text(
                                  isTl ? 'PANINDA' : 'ITEM',
                                  style: const TextStyle(fontWeight: FontWeight.w900),
                                ),
                              ),
                              Expanded(
                                flex: 2,
                                child: Text(
                                  isTl ? 'STOCK' : 'LEFT',
                                  textAlign: TextAlign.center,
                                  style: const TextStyle(fontWeight: FontWeight.w900),
                                ),
                              ),
                              Expanded(
                                flex: 2,
                                child: Text(
                                  isTl ? 'BILHIN' : 'BUY',
                                  textAlign: TextAlign.center,
                                  style: const TextStyle(fontWeight: FontWeight.w900),
                                ),
                              ),
                              Expanded(
                                flex: 3,
                                child: Text(
                                  isTl ? 'PUHUNAN' : 'EST.COST',
                                  textAlign: TextAlign.right,
                                  style: const TextStyle(fontWeight: FontWeight.w900),
                                ),
                              ),
                            ],
                          ),
                          const Padding(
                            padding: EdgeInsets.symmetric(vertical: 6),
                            child: Text(
                              '----------------------------------------',
                              textAlign: TextAlign.center,
                              maxLines: 1,
                              overflow: TextOverflow.clip,
                            ),
                          ),
                          if (lowStockItems.isEmpty)
                            Padding(
                              padding: const EdgeInsets.symmetric(vertical: 20),
                              child: Text(
                                isTl
                                    ? 'Kumpleto pa ang lahat ng paninda! Walang low-stock items ngayon.'
                                    : 'All shelves are well-stocked! No low-stock items right now.',
                                textAlign: TextAlign.center,
                                style: const TextStyle(
                                  fontWeight: FontWeight.w600,
                                  color: Color(0xFF475569),
                                ),
                              ),
                            )
                          else
                            ...lowStockItems.map((p) {
                              final buyQty = _suggestedBuyQty(p);
                              final estCost = buyQty * _unitEstimatedCostCents(p);
                              return Padding(
                                padding: const EdgeInsets.symmetric(vertical: 4),
                                child: Row(
                                  children: [
                                    Expanded(
                                      flex: 4,
                                      child: Text(
                                        '☐ ${p.name}',
                                        style: const TextStyle(
                                          fontWeight: FontWeight.w700,
                                          fontSize: 11.5,
                                        ),
                                      ),
                                    ),
                                    Expanded(
                                      flex: 2,
                                      child: Text(
                                        '${p.stockQty}',
                                        textAlign: TextAlign.center,
                                        style: const TextStyle(
                                          color: AppTheme.dangerRed,
                                          fontWeight: FontWeight.w800,
                                        ),
                                      ),
                                    ),
                                    Expanded(
                                      flex: 2,
                                      child: Text(
                                        '+$buyQty',
                                        textAlign: TextAlign.center,
                                        style: const TextStyle(
                                          color: AppTheme.primaryGreen,
                                          fontWeight: FontWeight.w800,
                                        ),
                                      ),
                                    ),
                                    Expanded(
                                      flex: 3,
                                      child: Text(
                                        CurrencyFormatter.format(estCost),
                                        textAlign: TextAlign.right,
                                        style: const TextStyle(
                                          fontWeight: FontWeight.w700,
                                        ),
                                      ),
                                    ),
                                  ],
                                ),
                              );
                            }),
                          const Padding(
                            padding: EdgeInsets.symmetric(vertical: 8),
                            child: Text(
                              '========================================',
                              textAlign: TextAlign.center,
                              maxLines: 1,
                              overflow: TextOverflow.clip,
                            ),
                          ),
                          Row(
                            mainAxisAlignment: MainAxisAlignment.spaceBetween,
                            children: [
                              Text(
                                isTl ? 'BILANG NG PANINDA:' : 'TOTAL ITEMS TO BUY:',
                                style: const TextStyle(fontWeight: FontWeight.w800),
                              ),
                              Text(
                                '${lowStockItems.length}',
                                style: const TextStyle(fontWeight: FontWeight.w900),
                              ),
                            ],
                          ),
                          const SizedBox(height: 4),
                          Row(
                            mainAxisAlignment: MainAxisAlignment.spaceBetween,
                            children: [
                              Text(
                                isTl ? 'TANTIYANG PUHUNAN:' : 'EST. PUHUNAN BUDGET:',
                                style: const TextStyle(
                                  fontWeight: FontWeight.w900,
                                  fontSize: 13,
                                ),
                              ),
                              Text(
                                CurrencyFormatter.format(totalBudgetCents),
                                style: const TextStyle(
                                  fontWeight: FontWeight.w900,
                                  fontSize: 14,
                                  color: AppTheme.primaryGreen,
                                ),
                              ),
                            ],
                          ),
                          const SizedBox(height: 12),
                          Text(
                            isTl
                                ? 'Dalhin ang receipt guide na ito sa palengke o grocery.'
                                : 'Bring this receipt checklist on your next market/wholesale run.',
                            textAlign: TextAlign.center,
                            style: const TextStyle(
                              fontSize: 10.5,
                              color: Color(0xFF64748B),
                            ),
                          ),
                        ],
                      ),
                    ),
                  ),
                ),
              ),
            ),

            Padding(
              padding: const EdgeInsets.fromLTRB(16, 8, 16, 16),
              child: Row(
                children: [
                  Expanded(
                    child: OutlinedButton.icon(
                      onPressed: () async {
                        await Clipboard.setData(ClipboardData(text: plainText));
                        if (!context.mounted) return;
                        ScaffoldMessenger.of(context).showSnackBar(
                          SnackBar(
                            content: Text(
                              isTl
                                  ? 'Nakopya na ang text ng receipt!'
                                  : 'Receipt text copied to clipboard!',
                            ),
                            backgroundColor: AppTheme.primaryGreen,
                          ),
                        );
                      },
                      icon: const Icon(Icons.copy_rounded, size: 18),
                      label: Text(isTl ? 'Kopyahin' : 'Copy Text'),
                    ),
                  ),
                  const SizedBox(width: 10),
                  Expanded(
                    flex: 2,
                    child: ElevatedButton.icon(
                      key: const Key('share_print_restock_receipt_btn'),
                      onPressed: _isSharing
                          ? null
                          : () => _shareReceiptImageOrText(
                                plainText: plainText,
                                isTl: isTl,
                              ),
                      icon: const Icon(Icons.print_rounded, size: 18),
                      label: Text(
                        isTl ? 'I-Print / I-Share Receipt' : 'Print / Share Receipt',
                      ),
                    ),
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }
}
